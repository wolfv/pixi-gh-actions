def main() -> None:
    parser = argparse.ArgumentParser(
        description="Execute a GitHub Actions workflow locally using pixi."
    )
    parser.add_argument(
        "workflow",
        type=Path,
        nargs="?",
        help="Path to the workflow YAML file (e.g. example-workflow.yml)",
    )
    parser.add_argument(
        "--job",
        help="Run only this specific job (default: all jobs)",
    )
    parser.add_argument(
        "--workspace",
        type=Path,
        default=Path.cwd(),
        help="GITHUB_WORKSPACE directory (default: current dir)",
    )
    parser.add_argument(
        "--build-only",
        action="store_true",
        help="Generate recipes and build packages, but do not execute the workflow",
    )
    parser.add_argument(
        "--no-rebuild",
        action="store_true",
        help="Skip building packages that are already present in ./channel/",
    )
    parser.add_argument(
        "--skip-build",
        action="store_true",
        help="Skip recipe generation and building entirely (assume env is already set up)",
    )
    args = parser.parse_args()

    if args.workflow is None and not args.build_only:
        parser.error("A workflow file is required unless --build-only is set.")

    if args.build_only:
        # Collect refs from all recipes/ subdirs
        refs: list[str] = []
        for recipe_yaml in RECIPES_DIR.rglob("recipe.yaml"):
            import yaml as _yaml
            with recipe_yaml.open() as f:
                r = _yaml.safe_load(f)
            ctx_block = r.get("context", {})
            owner = ctx_block.get("owner")
            repo = ctx_block.get("repo")
            version = ctx_block.get("version")
            if owner and repo and version:
                refs.append(f"{owner}/{repo}@v{version}")
        if not refs:
            print("No recipes found in ./recipes/. Run generate_recipe.py first.")
            return
        prepare_environment(refs, rebuild=not args.no_rebuild)
        print("\nDone. Environment is ready.")
        return

    workflow = load_workflow(args.workflow)
    action_refs = collect_action_refs(workflow)

    print(f"Found {len(action_refs)} action(s) in {args.workflow}:")
    for ref in action_refs:
        print(f"  {ref}")

    if not action_refs:
        print("No `uses:` steps found. Nothing to install.")
        env_prefix = pixi_env_prefix() if PIXI_TOML.exists() else Path("/")
    elif args.skip_build:
        print("\nSkipping build (--skip-build). Using existing pixi environment.")
        env_prefix = pixi_env_prefix()
        if not env_prefix.exists():
            sys.exit(f"Pixi env not found at {env_prefix}. Run without --skip-build first.")
    else:
        env_prefix = prepare_environment(action_refs, rebuild=not args.no_rebuild)

    print(f"\n=== Executing workflow: {args.workflow} ===")
    run_workflow(
        workflow_path=args.workflow,
        job_name=args.job,
        workspace=args.workspace.resolve(),
        env_prefix=env_prefix,
    )
    print("\nWorkflow complete.")


if __name__ == "__main__":
    main()
